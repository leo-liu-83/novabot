  const KEY = 'novabot.web.locale';
  // 英文词典独立成 i18n.en.js（键＝中文原文），运行时合并，避免把两套文案塞在同一个文件里
  Object.assign(dictionaries.en, window.NB_I18N_EN || {});
  const normalize = (value) => String(value || '').toLowerCase().startsWith('en') ? 'en' : 'zh';
  const missing = new Set();
  let saved = '';
  try { saved = localStorage.getItem(KEY) || ''; } catch (e) { /* file:// / privacy mode */ }
  let locale = normalize(saved || navigator.language || 'zh');

  function t(key, vars) {
    const fallback = dictionaries.zh[key] || key;
    let value = dictionaries[locale] && dictionaries[locale][key];
    if (!value) {
      value = fallback;
      if (locale !== 'zh' && !missing.has(key)) {
        missing.add(key);
        try {
          if (localStorage.getItem('novabot.web.i18nDebug') === '1') console.warn('[i18n] missing key:', locale, key);
        } catch (e) { /* debug is opt-in */ }
      }
    }
    Object.keys(vars || {}).forEach((name) => {
      value = value.replaceAll('{' + name + '}', String(vars[name]));
    });
    return value;
  }

  function setLocale(next) {
    locale = normalize(next);
    try { localStorage.setItem(KEY, locale); } catch (e) { /* language still changes for this page */ }
    document.documentElement.lang = locale === 'en' ? 'en' : 'zh-CN';
    window.dispatchEvent(new CustomEvent('nb:locale', { detail: { locale } }));
    return locale;
  }

  function has(key) {
    return !!(dictionaries[locale] && dictionaries[locale][key]);
  }

  function dateLocale() { return locale === 'en' ? 'en-US' : 'zh-CN'; }
  document.documentElement.lang = dateLocale() === 'en-US' ? 'en' : 'zh-CN';

  window.NB = window.NB || {};
  window.NB.i18n = { t, setLocale, has, locale: () => locale, dateLocale, dictionaries };
